def formatDeadliftChart(rawDeadliftChart):
    rows = rawDeadliftChart.strip().split('\n')

    for i in range(len(rows)):
        row = rows[i]
        columns = row.split()
        new_columns = []
        for column in columns:
            if (column == '---'):
                new_columns.append(999)
            else:
                new_columns.append(column)
        line_str = "["
        for i in range(len(new_columns) - 1):
           column = new_columns[i]
           line_str += f"{column}, "
        line_str += f"{new_columns[-1]}],"
        print(line_str)

