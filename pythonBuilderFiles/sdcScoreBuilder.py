import math

def formatSDCChart(rawSDCChart):
    rows = rawSDCChart.strip().split('\n')

    for i in range(len(rows)):
        row = rows[i]
        columns = row.split()
        new_columns = []
        for column in columns:
            if (column == '---'):
                new_columns.append(0)
            else:
                if ":" in column:
                    times = column.split(":")
                    minutes = float(times[0])
                    seconds = float(times[1])
                    total_time = minutes + math.ceil(seconds * 1000.0 / 60.0) / 1000.0
                    new_columns.append(total_time)
                else:
                    new_columns.append(column)
        line_str = "["
        for i in range(len(new_columns) - 1):
           column = new_columns[i]
           line_str += f"{column}, "
        line_str += f"{new_columns[-1]}],"
        print(line_str)

